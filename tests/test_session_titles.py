def test_codex_skill_links_and_markdown_links_become_words():
    got = titles.text_candidate("[$spec](C:\\Home\\x\\\\.claude\\skills\\spec\\SKILL.md) I need reddit access")
    assert got[0] == "/spec I need reddit access"
    assert titles.readable("see [the docs](https://example.com/a/b) now") == "see the docs now"


def test_paths_shrink_to_their_last_part_but_word_pairs_survive():
    assert titles.readable('@"C:\\Home\\x\\Documents\\Projects\\file_inbox\\snap_p1.md" process it') == \
        "snap_p1.md process it"
    assert titles.readable("Read audit/2026-09-26-claude-brief.md and execute") == \
        "Read 2026-09-26-claude-brief.md and execute"
    assert titles.readable("spin up sonnet/opus agents and/or codex") == "spin up sonnet/opus agents and/or codex"


def test_html_entities_and_markdown_escapes_are_undone():
    assert titles.readable("&#x20;Validate the work in the condo\\_options folder") == \
        "Validate the work in the condo_options folder"


def test_brief_preambles_are_dropped():
    assert titles.polish("User asks 2026-09-26: Dispatch an agent to spec the speaker") == \
        "Dispatch an agent to spec the speaker"
    assert titles.polish("Read-only research for a spec, no edits or installs. Research Reddit API access") == \
        "Research Reddit API access"
    assert titles.polish("Use the log skill to separately record this failure") == \
        "/log separately record this failure"


def test_clip_cuts_at_a_word_boundary():
    text = "Audit current loom os work, write suggested improvements, possible choices"
    got = titles.clip(text, 44)
    assert got == "Audit current loom os work, write suggested…"
    assert len(got) <= 44


def test_untitled_names_project_and_age():
    assert titles.untitled("hiking_log_v2", "1d") == "untitled · hiking_log_v2 · 1d"
    assert titles.age_text(90) == "1m" and titles.age_text(7200) == "2h"


