# ---------------------------------------------------------------- git stop points

def tool_use(tid, command, ts, name="Bash"):
    return {"type": "assistant", "timestamp": ts,
            "message": {"content": [{"type": "tool_use", "id": tid, "name": name,
                                     "input": {"command": command}}]}}


def tool_result(tid, is_error=False):
    return user([{"type": "tool_result", "tool_use_id": tid, "content": "ok", "is_error": is_error}])


def test_git_ops_reads_the_subcommand_not_prose():
    assert gitmarks.git_ops('git add -A && git commit -m "x" && git push') == {"commit", "push"}
    assert gitmarks.git_ops("git -C /c/repo push -u origin main") == {"push"}
    assert gitmarks.git_ops("git --no-pager log --oneline") == set()
    assert gitmarks.git_ops("claude -p 'use git and then commit the result'") == set()


def test_marks_count_only_successful_calls(tmp_path):
    p = write(tmp_path / "g.jsonl", [
        tool_use("t1", 'git commit -m "one"', "2026-09-26T10:00:00Z"), tool_result("t1"),
        tool_use("t2", "git push", "2026-09-26T10:05:00Z"), tool_result("t2"),
        tool_use("t3", 'git commit -m "nothing"', "2026-09-26T10:10:00Z"), tool_result("t3", is_error=True),
        tool_use("t4", 'git commit -am "two"', "2026-09-26T10:20:00Z", name="PowerShell"), tool_result("t4"),
    ])
    marks = gitmarks.marks_for(p)
    assert marks.last_commit_at == "2026-09-26T10:20:00Z"
    assert marks.last_push_at == "2026-09-26T10:05:00Z"
    conv = transcript_mod.load(p)
    assert (conv.last_commit_at, conv.last_push_at) == (marks.last_commit_at, marks.last_push_at)


def test_marks_read_only_the_appended_bytes(tmp_path):
    p = write(tmp_path / "inc.jsonl", [tool_use("t1", "git push", "2026-09-26T10:00:00Z")])
    assert gitmarks.marks_for(p).last_push_at is None   # no result yet
    with open(p, "a", encoding="utf-8") as fh:
        fh.write(json.dumps(tool_result("t1")) + "\n")
    assert gitmarks.marks_for(p).last_push_at == "2026-09-26T10:00:00Z"


def test_codex_command_executions_count_on_exit_code_zero(tmp_path):
    def done(cmd, code, ts):
        return {"type": "event_msg", "timestamp": ts, "payload": {"type": "item_completed", "item": {
            "type": "CommandExecution", "command": ["pwsh.exe", "-Command", cmd], "exit_code": code}}}
    p = write(tmp_path / "rollout-x.jsonl", [
        done("git -C $repo commit -m x; git -C $repo push", "0", "2026-09-26T23:39:58Z"),
        done("git push", "1", "2026-09-26T23:50:00Z"),
    ])
    marks = gitmarks.marks_for(p)
    assert marks.last_push_at == "2026-09-26T23:39:58Z"
    assert marks.last_commit_at == "2026-09-26T23:39:58Z"


def test_stop_point_text_words():
    now = datetime(2026, 9, 26, 12, 0, tzinfo=timezone.utc)
    iso = lambda minutes: (now - timedelta(minutes=minutes)).isoformat().replace("+00:00", "Z")
    pushed = m.SessionEntry("s", m.RECENT, "p", "", "t", last_commit_at=iso(10), last_push_at=iso(4))
    committed = m.SessionEntry("s", m.RECENT, "p", "", "t", last_commit_at=iso(12), last_push_at=iso(90))
    never = m.SessionEntry("s", m.RECENT, "p", "", "t")
    assert gitmarks.stop_point_text(pushed, now) == "pushed 4m"
    assert gitmarks.stop_point_text(committed, now) == "committed 12m"
    assert gitmarks.stop_point_text(never, now) == "never pushed"


def test_recent_entries_carry_the_marks(tmp_path):
    home = tmp_path / "claude"
    folder = home / "projects" / "C--x-proj"
    folder.mkdir(parents=True)
    write(folder / "s1.jsonl", [
        {"type": "user", "cwd": "C:/x/proj", "message": {"content": "ship the thing"}},
        tool_use("t1", "git push", "2026-09-26T10:00:00Z"), tool_result("t1"),
    ])
