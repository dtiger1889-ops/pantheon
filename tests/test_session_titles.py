def user(content, **extra) -> dict:
    return {"type": "user", "message": {"role": "user", "content": content}, **extra}


def cand(rec):
    got = titles.user_record_candidate(rec)
    return got[0] if got else None


# ---------------------------------------------------------------- skip rules, one each

def test_a_plain_first_message_is_the_title():
    assert cand(user("fix the launcher so F9 goes back to the deck")) == \
        "fix the launcher so F9 goes back to the deck"


def test_skill_body_is_skipped():
    rec = user([{"type": "text", "text": "Base directory for this skill: C:\\Home\\x\\skills\\spec\n\n# Spec"}])
    assert cand(rec) is None


def test_meta_records_are_skipped_even_with_ordinary_text():
    assert cand(user("Continue from where you left off.", isMeta=True)) is None


def test_command_wrapper_becomes_the_command_and_its_args():
    text = ("<command-message>orchestrate</command-message>\n<command-name>/orchestrate</command-name>\n"
            "<command-args>fix the deck</command-args>")
    assert titles.user_record_candidate(user(text)) == ("/orchestrate fix the deck", titles.STRONG)


def test_setup_commands_are_skipped():
    text = "<command-name>/model</command-name>\n<command-message>model</command-message>\n<command-args>fable</command-args>"
    assert cand(user(text)) is None


def test_a_bare_command_is_only_a_weak_title():
    text = "<command-name>/checkpoint</command-name><command-message>checkpoint</command-message><command-args></command-args>"
    assert titles.user_record_candidate(user(text)) == ("/checkpoint", titles.WEAK)


def test_agents_md_and_claude_md_injections_are_skipped():
    assert cand(user("# AGENTS.md instructions for C:\\Home\\x\\loom-os\n\n<INSTRUCTIONS>")) is None
    assert cand(user("# CLAUDE.md\nContents of C:\\x\\CLAUDE.md")) is None
    assert cand(user("Contents of C:\\Home\\x\\.claude\\CLAUDE.md (user's private)")) is None


def test_system_reminders_hook_output_and_local_command_output_are_skipped():
    assert cand(user("<system-reminder>be nice</system-reminder>")) is None
    assert cand(user("<local-command-caveat>Caveat: generated by local commands</local-command-caveat>")) is None
    assert cand(user("<local-command-stdout>Set model to Fable</local-command-stdout>")) is None
    assert cand(user("Stop hook feedback:\n[powershell ...]: PRIVATE REPO PUSH GATE")) is None


def test_tool_results_are_skipped():
    rec = user([{"type": "tool_result", "tool_use_id": "t1", "content": "1\tLast updated"}])
    assert cand(rec) is None
    assert cand(user("ok", toolUseResult={"stdout": ""})) is None


def test_image_only_messages_are_skipped_and_image_markers_dropped():
    only_images = user([{"type": "image", "source": {"type": "base64", "data": "AAAA"}}])
    assert cand(only_images) is None
    mixed = user([{"type": "image", "source": {}}, {"type": "text", "text": "[Image #1] why is this red"}])
    assert cand(mixed) == "why is this red"


def test_compact_summaries_and_sidechains_are_skipped():
    assert cand(user("This session is being continued from a previous conversation that ran out")) is None
    assert cand(user("real words", isCompactSummary=True)) is None
    assert cand(user("sub-agent brief", isSidechain=True)) is None


def test_scheduled_task_runs_get_a_weak_readable_name():
    rec = user('<scheduled-task name="loom-os-night-wind-down" file="C:\\x\\SKILL.md">\nThis is an automated run')
    assert titles.user_record_candidate(rec) == ("scheduled: loom os night wind down", titles.WEAK)


def test_short_replies_are_weak():
    assert titles.user_record_candidate(user("Try again"))[1] == titles.WEAK


